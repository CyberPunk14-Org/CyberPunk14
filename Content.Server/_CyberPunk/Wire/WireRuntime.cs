    private static string Unescape(string s)
    {
        var output = new StringBuilder(s.Length);
        for (var i = 0; i < s.Length; i++)
        {
            if (s[i] != '\\' || i + 1 == s.Length)
            {
                output.Append(s[i]);
                continue;
            }

            i++;
            output.Append(s[i] == 'n' ? '\n' : s[i]);
        }

        return output.ToString();
    }

